import { DateTime } from 'luxon';
import { Mod } from '../../model/tag';
import { Template } from '../../model/template';

const carouselLabels = {
  previous: $localize`Previous`,
  next: $localize`Next`,
  empty: $localize`No results found`,
};
const carouselLabelsSource = JSON.stringify(carouselLabels).replace(/</g, '\\u003c');

export const carouselTemplate: Template = {
  tag: 'carousel',
  name: $localize`🎠️ Carousel`,
  config: {
    mod: $localize`🎠️ Carousel`,
    version: 1,
    type: 'lens',
    global: true,
    view: $localize`🎠️`,
    tab: $localize`carousel`,
    generated: $localize`Generated by jasper-ui ${DateTime.now().toISO()}`,
    description: $localize`Show results in a carousel. More results stream in as you scroll.`,
    form: [{
      key: 'peek',
      type: 'number',
      defaultValue: 1,
      props: {
        label: $localize`Neighbours:`,
        title: $localize`Number of slides visible on each side of the current slide (0 to 3).`,
        min: 0,
        max: 3,
      },
    }],
    // language=CSS
    css: `
      .carousel-frame {
        --peek: 1;
        --slide: calc(100cqw / (1 + 2 * var(--peek)));
        container-type: inline-size;
        position: relative;
        outline: none;
      }
      .carousel-track {
        position: relative;
        display: flex;
        overflow-x: auto;
        scroll-snap-type: x mandatory;
        scrollbar-width: none;
        padding-inline: calc(var(--slide) * var(--peek));
        overscroll-behavior-x: contain;
      }
      .carousel-track::-webkit-scrollbar {
        display: none;
      }
      .carousel-slide {
        flex: 0 0 var(--slide);
        box-sizing: border-box;
        height: 60vh;
        padding: 8px;
        scroll-snap-align: center;
        scroll-snap-stop: always;
        display: flex;
        flex-direction: column;
        overflow: hidden;
        opacity: 0.5;
        transform: scale(0.85);
        transition: transform 0.3s ease, opacity 0.3s ease;
      }
      .carousel-slide.active {
        opacity: 1;
        transform: none;
      }
      .carousel-media {
        flex: 1 1 auto;
        min-height: 0;
        overflow: auto;
        border-radius: 8px;
        background: var(--card);
      }
      .carousel-media img,
      .carousel-media video {
        max-width: 100%;
        max-height: 100%;
        object-fit: contain;
      }
      .carousel-caption {
        flex: 0 0 auto;
        max-height: 30%;
        overflow: hidden;
      }
      .carousel-prev,
      .carousel-next {
        position: absolute;
        top: 50%;
        z-index: 1;
        transform: translateY(-50%);
        width: 40px;
        height: 40px;
        border-radius: 20px;
        font-size: 24px;
        line-height: 1;
        cursor: pointer;
        opacity: 0.7;
      }
      .carousel-prev:hover,
      .carousel-next:hover {
        opacity: 1;
      }
      .carousel-prev:disabled,
      .carousel-next:disabled {
        opacity: 0.2;
        cursor: default;
      }
      .carousel-prev {
        left: 4px;
      }
      .carousel-next {
        right: 4px;
      }
      .carousel-empty {
        padding: 16px;
        text-align: center;
      }
      @media (prefers-reduced-motion: reduce) {
        .carousel-slide {
          transition: none;
        }
      }
    `,
    // language=HTML
    snippet: `
    <script>
      Handlebars.registerHelper('carousel', function(page, actions, el, peek) {
        return function() {
          carouselApp(el.querySelector('.carousel-frame'), actions, page, peek);
        };
      });

      function carouselApp(root, actions, page, peek) {
        const labels = ${carouselLabelsSource};
        const track = root.querySelector('.carousel-track');
        const prev = root.querySelector('.carousel-prev');
        const next = root.querySelector('.carousel-next');
        prev.title = labels.previous;
        prev.setAttribute('aria-label', labels.previous);
        next.title = labels.next;
        next.setAttribute('aria-label', labels.next);
        peek = Math.max(0, Math.min(3, Math.floor(Number(peek ?? 1)) || 0));
        root.style.setProperty('--peek', peek);

        const slides = [];
        const urls = new Set();
        let pageNumber = -1;
        let pageSize;
        let last = false;
        let fetching = false;
        let active = -1;
        let destroyed = false;
        let frame;

        const observer = new IntersectionObserver(entries => {
          for (const e of entries) {
            const slide = slides[e.target.dataset.index];
            if (e.isIntersecting) {
              mount(slide);
            } else {
              unmount(slide);
            }
          }
        }, { root: track, rootMargin: '0px 100% 0px 100%' });

        function mount(slide) {
          if (slide.destroy) return;
          const destroyMedia = actions.embed(slide.media, slide.ref);
          const destroyCaption = actions.ref(slide.caption, slide.ref);
          slide.destroy = () => {
            destroyMedia();
            destroyCaption();
          };
        }
        function unmount(slide) {
          slide.destroy?.();
          slide.destroy = undefined;
        }

        function add(p) {
          pageNumber = p.page.number;
          pageSize = p.page.size;
          last = pageNumber >= p.page.totalPages - 1 || !p.content.length;
          for (const ref of p.content) {
            if (urls.has(ref.url + ' ' + ref.origin)) continue;
            urls.add(ref.url + ' ' + ref.origin);
            const el = document.createElement('div');
            el.className = 'carousel-slide';
            el.dataset.index = slides.length;
            const media = document.createElement('div');
            media.className = 'carousel-media';
            const caption = document.createElement('div');
            caption.className = 'carousel-caption';
            el.append(media, caption);
            el.addEventListener('click', () => {
              const i = slides.findIndex(s => s.el === el);
              if (i !== active) go(i);
            });
            track.append(el);
            const slide = { el, ref, media, caption };
            slides.push(slide);
            observer.observe(el);
          }
          if (!slides.length) {
            const empty = document.createElement('div');
            empty.className = 'carousel-empty';
            empty.textContent = labels.empty;
            track.replaceChildren(empty);
          }
          updateActive();
        }

        function more() {
          if (fetching || last || destroyed) return;
          fetching = true;
          actions.fetch(pageNumber + 1, pageSize).then(p => {
            fetching = false;
            if (!destroyed) add(p);
          }, () => {
            fetching = false;
            last = true;
          });
        }

        function center(i) {
          const slide = slides[i].el;
          return slide.offsetLeft - (track.clientWidth - slide.offsetWidth) / 2;
        }

        function go(i) {
          if (!slides.length) return;
          i = Math.max(0, Math.min(slides.length - 1, i));
          track.scrollTo({ left: center(i), behavior: matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth' });
        }

        function updateActive() {
          frame = undefined;
          if (!slides.length) {
            prev.disabled = next.disabled = true;
            return;
          }
          let best = 0;
          let distance = Infinity;
          for (let i = 0; i < slides.length; i++) {
            const d = Math.abs(center(i) - track.scrollLeft);
            if (d < distance) {
              distance = d;
              best = i;
            }
          }
          if (best !== active) {
            slides[active]?.el.classList.remove('active');
            slides[best].el.classList.add('active');
            active = best;
          }
          prev.disabled = active === 0;
          next.disabled = last && active === slides.length - 1;
          if (active >= slides.length - 1 - peek - 2) more();
        }

        const onScroll = () => frame ??= requestAnimationFrame(updateActive);
        track.addEventListener('scroll', onScroll, { passive: true });
        prev.addEventListener('click', () => go(active - 1));
        next.addEventListener('click', () => go(active + 1));
        root.addEventListener('keydown', e => {
          if (e.target !== root && e.target !== track) return;
          if (e.key === 'ArrowLeft') go(active - 1);
          else if (e.key === 'ArrowRight') go(active + 1);
          else if (e.key === 'Home') go(0);
          else if (e.key === 'End') go(slides.length - 1);
          else return;
          e.preventDefault();
        });
        const resize = new ResizeObserver(() => onScroll());
        resize.observe(track);

        actions.onDestroy(() => {
          destroyed = true;
          observer.disconnect();
          resize.disconnect();
          if (frame) cancelAnimationFrame(frame);
          slides.forEach(unmount);
        });

        if (page) {
          add(page);
        } else {
          more();
        }
      }
    </script>
    `,
    // language=Handlebars
    listUi: `
      <div class="carousel-frame" tabindex="0">
        <button class="carousel-prev" type="button">‹</button>
        <div class="carousel-track"></div>
        <button class="carousel-next" type="button">›</button>
      </div>
      {{defer el (carousel page actions el peek)}}
    `,
  },
  schema: {
    optionalProperties: {
      peek: { type: 'uint8' },
    },
  },
};

export const carouselMod: Mod = {
  template: [
    carouselTemplate,
  ],
};
